#!/usr/bin/env bash
# Regenerates app/src/main/res/layout/widget_<key>.xml, one per font.
# RemoteViews has no remotable setTypeface, so each font needs its own layout.
# Keys must match Font entries in Prefs.kt.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=app/src/main/res/layout
declare -A FONTS=(
  [sans]="sans-serif"
  [sans_light]="sans-serif-light"
  [sans_medium]="sans-serif-medium"
  [condensed]="sans-serif-condensed"
  [serif]="serif"
  [mono]="monospace"
)
for key in "${!FONTS[@]}"; do
  f=${FONTS[$key]}
  cat > "$OUT/widget_$key.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-layouts.sh (font: $f). Do not edit by hand. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/root"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="@drawable/widget_bg"
    android:gravity="center_vertical"
    android:orientation="vertical"
    android:padding="14dp">

    <LinearLayout
        android:layout_width="wrap_content"
        android:layout_height="wrap_content"
        android:baselineAligned="true"
        android:orientation="horizontal">
        <TextView
            android:id="@+id/label_local"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginEnd="10dp"
            android:fontFamily="$f"
            android:letterSpacing="0.1"
            android:text="@string/label_local"
            android:textColor="#B0BEC5"
            android:textSize="12sp" />
        <TextClock
            android:id="@+id/clock_local"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:fontFamily="$f"
            android:format12Hour="HH:mm"
            android:format24Hour="HH:mm"
            android:includeFontPadding="false"
            android:textColor="#FFFFFF"
            android:textSize="34sp" />
    </LinearLayout>

    <TextView
        android:id="@+id/zone_local"
        android:layout_width="wrap_content"
        android:layout_height="wrap_content"
        android:fontFamily="$f"
        android:textColor="#B0BEC5"
        android:textSize="12sp" />

    <TextClock
        android:id="@+id/date_local"
        android:layout_width="wrap_content"
        android:layout_height="wrap_content"
        android:fontFamily="$f"
        android:format12Hour="EEE d MMM yyyy"
        android:format24Hour="EEE d MMM yyyy"
        android:textColor="#B0BEC5"
        android:textSize="12sp" />

    <LinearLayout
        android:layout_width="wrap_content"
        android:layout_height="wrap_content"
        android:layout_marginTop="6dp"
        android:baselineAligned="true"
        android:orientation="horizontal">
        <TextView
            android:id="@+id/label_utc"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginEnd="10dp"
            android:fontFamily="$f"
            android:letterSpacing="0.1"
            android:text="@string/label_utc"
            android:textColor="#81D4FA"
            android:textSize="12sp" />
        <TextClock
            android:id="@+id/clock_utc"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:fontFamily="$f"
            android:format12Hour="HH:mm"
            android:format24Hour="HH:mm"
            android:includeFontPadding="false"
            android:textColor="#81D4FA"
            android:textSize="34sp"
            android:timeZone="UTC" />
    </LinearLayout>

    <TextClock
        android:id="@+id/date_utc"
        android:layout_width="wrap_content"
        android:layout_height="wrap_content"
        android:fontFamily="$f"
        android:format12Hour="EEE d MMM yyyy"
        android:format24Hour="EEE d MMM yyyy"
        android:textColor="#81D4FA"
        android:textSize="12sp"
        android:timeZone="UTC" />
</LinearLayout>
XML
done
echo "generated ${#FONTS[@]} layouts"
